#!/usr/bin/env python3
"""Stereo width and level touch-up applied to a finished set of preset files (Patch 7).

  post_fit.py IN_DIR OUT_DIR

The shipped set is a per-preset choice between two converter runs (pick_best.py), so it cannot be regenerated by the
converter alone; this step works on the files themselves. For each preset: render its state, pool the side and mid power
over the part that sounds (six renders, random unison phases) and compare with Serum's full-chain render. Master Width is
scaled by the difference in dB (kept only if a re-render lands at least MIN_GAIN_DB closer), then the volume is nudged so
the RMS matches Serum's again (only if more than 0.5 dB off, and never past the pot's ends). Writes OUT_DIR/*.json and
calibration/post_fit.json.
"""
import json
import os
import re
import sys
import threading
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "calibration"))
os.chdir(ROOT)
import numpy as np
import fit_chain as C
import fit_level as L
import test_render_calibration as H

H.LOG_PATH = ROOT / "calibration/post_fit.log"
log = H.log
SR = H.SR
MIN_ERROR_DB, MIN_GAIN_DB, RENDERS = 2.0, 1.5, 6


def pooled_db(runs, end):
    s = m = 0.0
    for r in runs:
        x = r[:, int(0.01 * SR):int(end * SR)]
        s += (((x[0] - x[1]) / 2) ** 2).sum()
        m += (((x[0] + x[1]) / 2) ** 2).sum()
    return float(10 * np.log10(max(s, 1e-20) / max(m, 1e-20)))


def setk(state, key, val):
    if re.search(rf"(^|;){key}=", state):
        return re.sub(rf"((?:^|;){key}=)[^;]*", rf"\g<1>{val}", state, count=1)
    return state + f"{key}={val};"


def getk(state, key, default):
    m = re.search(rf"(?:^|;){key}=([^;]*)", state)
    return float(m.group(1)) if m else default


def fit_item(it, state):
    rend = lambda st, n=RENDERS: [H.run_cli(st, it["notes"], C.DUR, C.HOLD) for _ in range(n)]
    target = pooled_db(it["refs"], it["end"])
    w0 = int(getk(state, "mwidth", 64))
    runs = rend(state)
    before = pooled_db(runs, it["end"])
    rec = {"target_db": target, "before_db": before, "width": [w0, w0]}
    new = state
    if abs(before - target) >= MIN_ERROR_DB and before > -60 and target > -60:
        pot = int(round(min(max(w0 * 10 ** (-(before - target) / 20.0), 0), 127)))
        cand = setk(state, "mwidth", pot)
        runs2 = rend(cand)
        after = pooled_db(runs2, it["end"])
        if pot != w0 and abs(after - target) <= abs(before - target) - MIN_GAIN_DB:
            new, runs, rec["width"], rec["after_db"] = cand, runs2, [w0, pot], after
    # level: the RMS of what is shipped, against Serum's
    serum_rms = L.rms_db(it["refs"], it["end"])
    d = serum_rms - L.rms_db(runs, it["end"])
    v0 = int(getk(new, "volume", 36))
    rec["level_db"] = d
    if abs(d) > 0.5:
        v = int(round(min(max(v0 * 10 ** (d / 40.0), 1), 127)))
        rec["volume"] = [v0, v]
        new = setk(new, "volume", v)
    return new, rec


def main():
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    dst.mkdir(parents=True, exist_ok=True)
    srcname = {H.d2m.ascii_name(p.stem): p.stem for p in H.PRESET_DIR.glob("*.SerumPreset")}
    log_data, lock = {}, threading.Lock()
    files = sorted(src.glob("*.json"))

    def work(f):
        n = srcname.get(f.stem, f.stem)
        j = json.loads(f.read_text(encoding="utf-8"))
        items = C.load_items([n])
        try:
            if not items:
                raise RuntimeError("no Serum reference")
            new, rec = fit_item(items[0], j["state"])
            j["state"] = new
        except Exception as e:
            rec = {"error": str(e)[:100]}
        (dst / f.name).write_text(json.dumps(j) + "\n", encoding="utf-8")
        with lock:
            log_data[f.stem] = rec
            if "after_db" in rec or "volume" in rec:
                log(f"  {f.stem:28s} side/mid serum {rec.get('target_db', 0):+6.1f} tablor {rec.get('before_db', 0):+6.1f}" +
                    (f" -> {rec['after_db']:+6.1f} (width {rec['width'][0]}->{rec['width'][1]})" if "after_db" in rec else "") +
                    (f"   volume {rec['volume'][0]}->{rec['volume'][1]} ({rec['level_db']:+.1f} dB)" if "volume" in rec else ""))
    with ThreadPoolExecutor(max_workers=6) as pool:
        list(pool.map(work, files))
    Path("calibration/post_fit.json").write_text(json.dumps(log_data, indent=1), encoding="utf-8")
    w = sum(1 for r in log_data.values() if "after_db" in r); v = sum(1 for r in log_data.values() if "volume" in r)
    log(f"\n{w} presets widened or narrowed, {v} volumes nudged, of {len(files)}")
    sys.stdout.flush()
    os._exit(0)


if __name__ == "__main__":
    H.LOG_PATH.write_text("", encoding="utf-8")
    main()
