#!/usr/bin/env python3
"""Generate src/dsp/dist_tables.h (Serum's Distortion FX modes as measured transfer curves) and calibration/dist_table_modes.json (the converter's index of them)
from calibration/probe_dist_fxtable.json (calibration/dev/probe_dist_fxtable.py). Run from schwung-tablor/:  python tools/gen_dist_tables.py

A mode goes in when its curve is a clean static shaper (Overdrive once its input has been through its 3rd-order high-pass, which the engine then runs too): the rising and falling halves of the measured cycle agree (median gap under GAP_MAX table units).
The folds (SineShaper / SinFold / LinFold) fold too fast for this probe at 131 Hz and Overdrive with NumStages > 1 is not one curve; those keep the converter's Soft / Asym / Hard / Sine fit. A mode's rows are blended
by Drive when blending two neighbouring rows predicts the row between them to BLEND_MAX; otherwise the engine takes the nearest row (5 % of Drive apart).

Scale: the table's input unit is Serum's warp unit, 1.70 x the probe sine's output (probe_dist_fxcurve.py), and its output is in the same units with Serum's 0.5; the engine
stage runs before its master gain, which at the probe preset's default master is DIST_PROBE_GAIN (converter/fxmap.py), so its input gain is 1.70 x that and its output 0.5 / that."""
import json, math
from pathlib import Path
import numpy as np
HERE = Path(__file__).resolve().parent.parent
REPO = HERE.parent
GAP_MAX, BLEND_MAX = 0.10, 0.06
DIST_PROBE_GAIN = 10 ** (-2.4186 / 20)          # converter/fxmap.py
d = json.loads((REPO / "calibration/probe_dist_fxtable.json").read_text())
x = np.array(d["x"]); tu = float(d["tu_per_probe_unit"])
modes, blend, prehp, rows = [], [], [], None
for m, r in d["modes"].items():
    f = np.array(r["f"])
    if np.isnan(f).any() or float(np.median(r["branch"])) > GAP_MAX:
        continue
    step = r["drives"][1] - r["drives"][0]
    assert all(abs(a - i * step) < 1e-6 for i, a in enumerate(r["drives"])) and r["drives"][-1] == 100, m
    rows = rows or len(r["drives"])
    assert rows == len(r["drives"])
    be = max(float(np.abs(f[i] - (f[i - 1] + f[i + 1]) / 2).max()) for i in range(1, len(f) - 1))
    modes.append((m, f)); blend.append(be <= BLEND_MAX)
    assert int(r.get("pre_hp_n", 1)) == 1, m                   # the engine runs the high-pass once (Overdrive NumStages 1)
    prehp.append(float(r.get("pre_hp_hz", 0.0)))
NP = len(x); RANGE = float(x[-1])
assert abs(x[0] + RANGE) < 1e-9
gin = tu * DIST_PROBE_GAIN; gout = 0.5 / (tu * DIST_PROBE_GAIN)
lines = ["/* GENERATED by tools/gen_dist_tables.py from calibration/probe_dist_fxtable.json - do not edit.",
         " * Serum's Distortion FX modes as measured transfer curves out = f(in) in its table units, %d points over -%g..%g, %d rows of Drive 0..100." % (NP, RANGE, RANGE, rows),
         " * Measured with calibration/dev/probe_dist_fxtable.py. Modes (dist_tab - 1): " + ", ".join(m for m, _ in modes) + ". */",
         "#pragma once", "namespace tb {",
         "constexpr int kDistTabModes = %d, kDistTabRows = %d, kDistTabPts = %d;" % (len(modes), rows, NP),
         "constexpr float kDistTabRange = %.1ff, kDistTabStep = %.1ff;" % (RANGE, 100.0 / (rows - 1)),
         "constexpr float kDistTabIn = %.5ff, kDistTabOut = %.5ff;      /* the engine stage's signal -> table units, and back (with Serum's 0.5) */" % (gin, gout),
         "static const bool kDistTabBlend[kDistTabModes] = { " + ", ".join("true" if b else "false" for b in blend) + " };",
         "static const float kDistTabPreHp[kDistTabModes] = { " + ", ".join("%.1ff" % h for h in prehp) + " };      /* a 3rd-order Butterworth high-pass ahead of the curve (Hz, 0 none): Overdrive's */",
         "static const float kDistTabData[kDistTabModes][kDistTabRows][kDistTabPts] = {"]
for m, f in modes:
    lines.append("  { /* %s */" % m)
    for row in f:
        lines.append("    {" + ",".join(("%.4f" % v).rstrip("0").rstrip(".") if abs(v) >= 5e-5 else "0" for v in row) + "},")
    lines.append("  },")
lines += ["};", "}  // namespace tb", ""]
(HERE / "src/dsp/dist_tables.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")
(REPO / "calibration/dist_table_modes.json").write_text(json.dumps({"modes": [m for m, _ in modes], "blend": blend, "pre_hp_hz": prehp, "rows": rows}, indent=1), encoding="utf-8")
print("modes", [m for m, _ in modes]); print("blend", blend); print("in %.4f out %.4f" % (gin, gout))
