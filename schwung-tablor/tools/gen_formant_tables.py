#!/usr/bin/env python3
"""Serum's three Formant voice filters as tables: src/dsp/formant_tables.h from calibration/formant_grid.json.

Measured (calibration/dev/probe_formant.py and the dense probe in docs/TRANSLATION_RULES.md): a held saw at nine low notes through Voice Filter 1, the level of every harmonic against the
unfiltered saw. Each (Freq, Var) transfer is the sum of parallel band-pass resonators (ONE five, TWO three, TWB four), fitted to 0.1 dB rms (TWB at the highest Var 0.5 dB). The grid
holds the fitted centre, bandwidth (Hz) and peak gain of every resonator (the gain is about 1.02 except in TWB at high Var, where two resonators merge and one sits above 9 kHz): Freq 0..1 in steps of 0.1 (the knob: note = 136.7 x Freq), Var 0..100 in steps of 12.5.

    python tools/gen_formant_tables.py        (from schwung-tablor/)
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
GRID = json.loads((ROOT.parent / "calibration" / "formant_grid.json").read_text())

out = ["#pragma once",
       "/* Generated by tools/gen_formant_tables.py from calibration/formant_grid.json: do not edit. Serum's Formant voice filters measured against the plugin (see formant.h). */",
       "namespace tb {",
       f"static constexpr int kSerumFormantX = {len(GRID['x'])}, kSerumFormantVar = {len(GRID['var'])};",
       "/* per model: [Freq][Var][resonator] = { centre Hz, bandwidth Hz, peak gain } */"]
counts = []
for name, cname in (("FormantONE", "One"), ("FormantTWO", "Two"), ("FormantTWB", "Twb")):
    m = GRID["models"][name]
    n = m["n"]
    counts.append(n)
    vals = []
    for x in GRID["x"]:
        for v in GRID["var"]:
            trip = m["fit"][f"{x}|{v}"]
            for t in trip:
                vals += [f"{t[0]:.1f}f", f"{t[1]:.1f}f", f"{t[2]:.3f}f"]
    out.append(f"static constexpr int kSerumFormant{cname}N = {n};")
    out.append(f"static const float kSerumFormant{cname}[{len(GRID['x'])} * {len(GRID['var'])} * {n} * 3] = {{")
    for i in range(0, len(vals), 12):
        out.append("    " + ", ".join(vals[i:i + 12]) + ",")
    out.append("};")
out.append("}  // namespace tb")
(ROOT / "src" / "dsp" / "formant_tables.h").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print("formant_tables.h:", sum(counts), "resonators per grid point over", len(GRID["x"]) * len(GRID["var"]), "points")
