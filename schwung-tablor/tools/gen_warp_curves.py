#!/usr/bin/env python3
"""Generate src/dsp/warp_curves.h (Serum's static waveshaper warps as measured transfer curves) and calibration/warp_curve_modes.json (the converter's small index of them)
from calibration/warp_curves_measured.json (calibration/dev/probe_warp_curves.py). Run from schwung-tablor/:  python tools/gen_warp_curves.py
A mode is usable up to the largest amount at which the curve measured from the sine still predicted the saw through the same warp to 10 % rms (and so at every amount below)."""
import json
from pathlib import Path
HERE = Path(__file__).resolve().parent.parent
REPO = HERE.parent
d = json.loads((REPO / "calibration/warp_curves_measured.json").read_text())
modes = list(d)
AM = d[modes[0]]["amounts"]; NP = len(d[modes[0]]["x"])
assert all(m["amounts"] == AM and len(m["x"]) == NP for m in d.values())
limit, noop = {}, {}
for m, r in d.items():
    lim = AM[-1]
    for a, e in zip(AM, r["err"]):
        if e > 0.10:
            lim = AM[AM.index(a) - 1]; break
    limit[m] = lim
    x = r["x"]; dev = [max(abs(f - xx) for f, xx in zip(row, x)) for row in r["f"]]
    # the largest amount below which the curve is the identity within 0.005
    n = 0
    while n < len(AM) and dev[n] < 0.005:
        n += 1
    noop[m] = AM[n - 1] if n else None
lines = ["/* GENERATED by tools/gen_warp_curves.py from calibration/warp_curves_measured.json - do not edit.",
         " * Serum's static waveshaper warps as transfer curves out = f(in), in table units (the Basic Shapes sine peaks at 1), %d points over -1..1, %d amounts 0..1." % (NP, len(AM)),
         " * Measured with calibration/dev/probe_warp_curves.py. Modes: " + ", ".join(modes) + ". */",
         "#pragma once", "namespace tb {",
         "constexpr int kWarpCurveModes = %d, kWarpCurveAmts = %d, kWarpCurvePts = %d;" % (len(modes), len(AM), NP),
         "static const float kWarpCurveData[kWarpCurveModes][kWarpCurveAmts][kWarpCurvePts] = {"]
for m in modes:
    lines.append("  { /* %s */" % m)
    for row in d[m]["f"]:
        lines.append("    {" + ",".join(("%.4f" % v).rstrip("0").rstrip(".") if v else "0" for v in row) + "},")
    lines.append("  },")
lines += ["};", "}  // namespace tb", ""]
(HERE / "src/dsp/warp_curves.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")
(REPO / "calibration/warp_curve_modes.json").write_text(json.dumps({"modes": modes, "limit": limit, "noop_below": noop, "amounts": AM}, indent=1), encoding="utf-8")
print("modes", modes); print("usable up to", limit); print("identity up to", noop)
